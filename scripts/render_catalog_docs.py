"""Render docs/decision-catalog.md, docs/metric-catalog.md and docs/identifiability-matrix.md from data/*.json."""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
DOCS = ROOT / "docs"

# Client-side formulas found in the REA-located module text (see docs/calculation-map.md).
CLIENT_FORMULA_MODULES = {
    "FixedCapacity": "units/quarter = units/day x 65; unit capacity cost = option cost / units",
    "OperatingCapacity": "quarterly = daily x maxDays(65); effective = OC x productivity / 100",
    "OperatingCapacityRegional": "quarterly = daily x maxDays(65); effective = OC x productivity / 100",
    "ExtFactorySimulation": "planned x 65 x productivity / 100; OC x 65",
    "ExtFactorySimulationRegional": "OC x productivity / 100; demand / 65",
    "DemandProjection": "brandDemand / 65; operatingCapacityNeeded / 65",
    "DemandProjectionRegional": "brandDemand / 65; regional share = demand x 100 / lqTotalDemand",
}
# (module, field) pairs whose what-if path was verified by an operator experiment.
VERIFIED_WHATIF = {("CD", "deposit"): "EXP-01"}
MARKET_OUTPUTS ="Sales / MarketShare / IncomeStatement actuals / BalancedScorecard"
NUMERIC = {"integer", "float", "boolean", "enum", "unknown", "list"}


def load(name: str) -> dict[str, Any]:
    data: dict[str, Any] = json.loads((DATA / name).read_text(encoding="utf-8"))
    return data


def _cell(value: Any) -> str:
    if value is None or value == "" or value == []:
        return "-"
    if isinstance(value, list):
        return ", ".join(str(item) for item in value)
    return str(value).replace("|", "/")


def render_decisions(decisions: dict[str, Any], calc_by_module: dict[str, list[str]]) -> str:
    rows = sorted(decisions["decisions"], key=lambda r: (not r.get("rendered_in_q1_menu"), r["module"]))
    lines = [
        "# Decision catalog",
        "",
        "Generated by `scripts/render_catalog_docs.py` from `data/decision_catalog.json`. That file is produced by",
        "`marketplace_sysid.rea_ingest` from REA Evidence `ev_7131e083…` (JS) and `ev_579388377f…` (capture).",
        "It holds structure only: no team values.",
        "",
        "* **Service** = class name. Every decision screen inherits `view/modify/calculate/save/cancel` and the lock methods.",
        "* **Bounds**: no numeric `min/max/step` is declared client-side. Controls carry only display options",
        "  (`size`, `rows`, `maxlength` on text). Bounds and required checks come back from the server",
        "  as `checkResult.errors` from **both** `calculate` and `save`.",
        "* **What-if** = the screen can call `<Service>.calculate(user, draftDecisions, 0)` without `save`",
        "  (live `bindCalculate` on input events, or a **Calculate** button). This needs the `modify` lock.",
        "* `Q1` = rendered in the captured Quarter 1 task list. Other screens are registered in the client but",
        "  were not seen in the Q1 menu; their quarter of appearance is unknown.",
        "",
        (f"Total: **{len(rows)}** screens "
         f"({sum(1 for r in rows if r.get('finalization'))} finalization, "
         f"{sum(1 for r in rows if r.get('whatif_path'))} with a what-if path, "
         f"{sum(1 for r in rows if r.get('rendered_in_q1_menu'))} in the Q1 menu)."),
        "",
        "| Module (service) | Q1 | Fields (type, live-calc) | What-if | Calculate outputs | Buttons in modify mode | REA module |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        fields = []
        for field in row.get("fields", []):
            flag = ""
            if field.get("triggers_live_calculate"):
                flag = " ⚡"
            elif field.get("recalculated_by_calculate_button"):
                flag = " 🔘"
            fields.append(f"`{field['field']}` ({field.get('value_type', '?')}){flag}")
        whatif = "FINALIZATION, never automate" if row.get("finalization") else ("yes" if row.get("whatif_path") else "no")
        lines.append(
            f"| {row['module']} | {'✓' if row.get('rendered_in_q1_menu') else ''} | {_cell(fields)} | {whatif} | "
            f"{_cell(calc_by_module.get(row['module'], [])[:12])} | {_cell(row.get('modify_mode_buttons'))} | "
            f"{_cell(row.get('rea_module_key'))} |"
        )
    lines += ["", "⚡ = the input is bound to a live `calculate` (500 ms debounce); 🔘 = recalculated by the Calculate button.", ""]
    return "\n".join(lines)


def render_metrics(metrics: dict[str, Any]) -> str:
    by_module: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in metrics["metrics"]:
        by_module[row["module"]].append(row)
    key_reports = ["Sales", "MarketShare", "MarketShareSupplier", "ChannelDemand", "BalancedScorecard",
                   "CumulativeBalancedScorecard", "FinanceReport", "FinancialPosition", "BrandProfitability",
                   "RegionalProfitability", "CostOfProduction", "ManufacturingResults", "PlayersStanding",
                   "ProFormaFinance", "Grades"]
    lines = [
        "# Metric catalog",
        "",
        "Generated from `data/metric_catalog.json` (structure only, no values).",
        "",
        "* `calculate`: returned by `<Service>.calculate` / `view` as `calculate`. If `available_before_save`, it",
        "  can be produced from draft decisions through the what-if path.",
        "* `view.staticData` / `view.dynamicData`: report fields rendered by the client after `view`. These are",
        "  server results for already-processed quarters (or projections from stored state).",
        "",
        "## Where the headline outcomes live",
        "",
        "| Outcome | Screen (service) | Data path | How it is produced |",
        "|---|---|---|---|",
        "| Unit sales | `Sales` | `staticData.officeSales / webSales / globalSales / outsourcingSales` | server, after quarter processing |",
        "| Revenue, COGS, operating profit | `IncomeStatement` (FinanceReport) and `ProFormaIncomeStatement` (ProFormaFinance) | `staticData.sections[].items[].quarters[]` (row names come from the server) | server; ProForma adds `fill` projection columns |",
        "| Market share | `MarketShare` | `staticData.segments / teams / demand`; client computes `% = demand x 100 / segment total` | server demand + client percentage |",
        "| Channel share | `ChannelDemand` | `soDemand x 100 / total`, `webDemand x 100 / total` | client percentage of server demand |",
        "| Balanced scorecard | `BalancedScorecard`, `CumulativeBalancedScorecard`, `DrillDownBSC` | `staticData.indicators` | server |",
        "| Operating profit (prior quarter) | `FinancialPosition` | `staticData.operatingProfitPriorQtr` | server |",
        "| Production cost per unit | `FactorySimulation` / `ExtFactorySimulation` (calculate) | `brandsForSale[].material / labor / overhead / prodCost / avgCost` | server, **what-if capable** |",
        "| Projected demand next quarter | `FixedCapacity` | `dynamicData.projectDemandNextQuarter` (client shows `/65` per day) | server, read-only |",
        "| Live pro forma gadget | `GameInfo.liveProForma([user])` | sections/items | server, from stored state (no draft parameter) |",
        "",
        "## Key report modules",
        "",
        "| Module | Fields read by the client |",
        "|---|---|",
    ]
    for module in key_reports:
        names = sorted({r["metric"] for r in by_module.get(module, [])})
        lines.append(f"| {module} | {_cell(names)} |")
    lines += ["", "## All modules", "", "| Module | Source | Metrics | Before save? | Observed in capture |", "|---|---|---|---|---|"]
    for module in sorted(by_module):
        groups: dict[str, list[dict[str, Any]]] = defaultdict(list)
        for row in by_module[module]:
            groups[row["source"]].append(row)
        for source, items in sorted(groups.items()):
            before = any(item.get("available_before_save") for item in items)
            observed = any(item.get("observed_in_capture") or "REA_CAPTURE_RECORD" in item.get("provenance", [])
                           for item in items)
            lines.append(f"| {module} | {source} | {_cell(sorted({i['metric'] for i in items}))} | "
                         f"{'yes' if before else 'no'} | {'yes' if observed else ''} |")
    lines.append("")
    return "\n".join(lines)


def render_matrix(decisions: dict[str, Any], calc_by_module: dict[str, list[str]]) -> str:
    lines = [
        "# Identifiability matrix",
        "",
        "For each decision field, this shows how its effect on each output group can be observed **today**.",
        ("The cells come from static evidence. `W✅` marks a pair whose what-if path an operator experiment verified at "
         "runtime (EXP-01, 2026-11-03: `CD.deposit`, no save, Cancel restored, interest slope = displayed rate/4)."),
        "",
        "| Code | Meaning |",
        "|---|---|",
        "| **F** | Known client-side formula (exact arithmetic in REA-located module text) |",
        "| **W** | Measurable through the what-if channel: `modify` → change → `calculate` → `cancel`, no `save` |",
        "| **P** | Needs `save` (a real, reversible write teammates see); then pro forma projections reflect it (INFERRED, EXP-09) |",
        "| **Q** | Needs quarter submission; observable next quarter, confounded by competitors |",
        "| **X** | Not numerically observable (free text, qualitative grading, or no channel) |",
        "| - | No expected relation |",
        "",
        ("Output groups: **own-calc** = the same screen's `calculate` outputs; **client** = client formulas; "
         f"**pro forma** = ProForma Income/Balance/Cash-flow projections; **market** = {MARKET_OUTPUTS}."),
        "",
        "| Module | Field | Type | own-calc | client | pro forma | market | Own-calc outputs |",
        "|---|---|---|---|---|---|---|---|",
    ]
    counts: dict[str, int] = defaultdict(int)
    for row in sorted(decisions["decisions"], key=lambda r: r["module"]):
        module = row["module"]
        for field in row.get("fields", []) or [{"field": "(none parsed)", "value_type": "unknown"}]:
            value_type = str(field.get("value_type", "unknown"))
            textual = value_type in {"text", "file"}
            if row.get("finalization"):
                cells = ["X", "-", "Q", "Q"]
            elif textual:
                cells = ["-", "-", "-", "X"]
            else:
                own = "W" if row.get("whatif_path") and calc_by_module.get(module) else "-"
                if own == "W" and (module, field["field"]) in VERIFIED_WHATIF:
                    own = f"W✅ ({VERIFIED_WHATIF[(module, field['field'])]})"
                client = "F" if module in CLIENT_FORMULA_MODULES else "-"
                cells = [own, client, "P", "Q"]
            for cell in cells:
                counts[cell] += 1
            lines.append(f"| {module} | `{field['field']}` | {value_type} | " + " | ".join(cells)
                         + f" | {_cell(calc_by_module.get(module, [])[:8])} |")
    lines += ["", "Cell counts: " + ", ".join(f"{k}={v}" for k, v in sorted(counts.items())), "",
              "## Client formulas referenced (F)", "", "| Module | Formula |", "|---|---|"]
    lines += [f"| {module} | {formula} |" for module, formula in CLIENT_FORMULA_MODULES.items()]
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    decisions = load("decision_catalog.json")
    metrics = load("metric_catalog.json")
    calc_by_module: dict[str, list[str]] = defaultdict(list)
    for row in metrics["metrics"]:
        if row["source"] == "calculate" and row["metric"] not in calc_by_module[row["module"]]:
            calc_by_module[row["module"]].append(row["metric"])
    (DOCS / "decision-catalog.md").write_text(render_decisions(decisions, calc_by_module), encoding="utf-8")
    (DOCS / "metric-catalog.md").write_text(render_metrics(metrics), encoding="utf-8")
    (DOCS / "identifiability-matrix.md").write_text(render_matrix(decisions, calc_by_module), encoding="utf-8")
    print("rendered 3 documents")


if __name__ == "__main__":
    main()
